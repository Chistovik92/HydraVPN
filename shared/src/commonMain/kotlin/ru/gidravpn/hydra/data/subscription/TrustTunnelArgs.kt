package ru.gidravpn.hydra.data.subscription

import ru.gidravpn.hydra.data.model.ServerProfile
import ru.gidravpn.hydra.data.model.TrustTunnelConfig

/**
 * Аргументы нативного `trusttunnel_client` (TrustTunnelClient, Apache-2.0).
 *
 * Схема — [ru.gidravpn.hydra.vpn.core.SocksBridgeCore]-подобная:
 * `trusttunnel_client --config <toml>` поднимает **SOCKS5** на `127.0.0.1:$socksPort`,
 * а sing-box берёт на себя tun/маршрутизацию/DNS (см. `TrustTunnelCore`,
 * `SingBoxConfigBuilder.buildXrayBridge`). Системный TUN и killswitch у клиента
 * ВЫКЛЮЧЕНЫ — управление сетью остаётся за Hydra (`VpnService`/sing-box).
 *
 * TOML-схема — как у `trusttunnel_client --setup-wizard` (см. upstream
 * `trusttunnel/README.md`): `[endpoint]` + `[listener.socks]`.
 */
object TrustTunnelArgs {

    /** Имя бинаря в `nativeLibraryDir` / `app/libs/trusttunnel/<abi>/`. */
    const val BINARY_NAME = "libtrusttunnel.so"

    /** Собрать TOML-конфиг `trusttunnel_client` из [profile] + [socksPort]. */
    fun buildToml(profile: ServerProfile, socksPort: Int, certificatePath: String? = null): String =
        buildToml(toConfig(profile), socksPort, certificatePath)

    /** Собрать TOML из готового [TrustTunnelConfig]. */
    fun buildToml(cfg: TrustTunnelConfig, socksPort: Int, certificatePath: String? = null): String = buildString {
        appendLine("# Generated by HydraVPN — do not edit. TrustTunnelClient schema (upstream trusttunnel/README.md).")
        appendLine("loglevel = \"info\"")
        appendLine("vpn_mode = \"general\"")
        appendLine("killswitch_enabled = false")          // управление сетью — у Hydra/sing-box
        appendLine("killswitch_allow_ports = []")
        appendLine("post_quantum_group_enabled = true")
        appendLine("exclusions = []")
        appendLine()
        appendLine("[endpoint]")
        appendLine("hostname = ${toml(cfg.effectiveHostname)}")
        if (cfg.effectiveSni != cfg.effectiveHostname) appendLine("custom_sni = ${toml(cfg.effectiveSni)}")
        appendLine("addresses = [${cfg.addresses.joinToString(", ") { toml(it) }}]")
        appendLine("has_ipv6 = ${cfg.hasIpv6}")
        appendLine("username = ${toml(cfg.username)}")
        appendLine("password = ${toml(cfg.password)}")
        appendLine("client_random = ${toml(cfg.clientRandom)}")
        appendLine("client_random_auth_key = ${toml(cfg.clientRandomAuthKey)}")
        appendLine("skip_verification = ${cfg.skipVerification}")
        // сертификат: путь к PEM во временном каталоге (пишет TrustTunnelCore) либо inline-PEM
        val cert = certificatePath ?: cfg.certificatePem
        appendLine("certificate = ${if (cert.isNullOrBlank()) "\"\"" else toml(cert)}")
        appendLine("dns_upstreams = [${cfg.dnsUpstreams.joinToString(", ") { toml(it) }}]")
        appendLine("upstream_protocol = ${toml(cfg.upstreamProtocol.wire)}")
        appendLine("tls_profile = ${toml(cfg.tlsProfile)}")
        appendLine("anti_dpi = ${cfg.antiDpi}")
        cfg.name?.let { appendLine("name = ${toml(it)}") }
        appendLine()
        appendLine("[listener.socks]")
        appendLine("address = ${toml("127.0.0.1:$socksPort")}")
        // без [listener.tun] — системный туннель не используем
    }

    /** Аргументы процесса: `--config <path>`. */
    fun processArgs(configPath: String): List<String> = listOf("--config", configPath)

    /** [ServerProfile] → [TrustTunnelConfig]. Секреты — `uuidOrPassword`; username — `extra.username`. */
    fun toConfig(profile: ServerProfile): TrustTunnelConfig {
        val extra = runCatching { org.json.JSONObject(profile.extra) }.getOrDefault(org.json.JSONObject())
        val address = "${hostForAddress(profile.address)}:${profile.port}"
        // username: явное поле → `user:pass` (до ':') → пусто (TrustTunnel требует username И password,
        // но если дали только пароль — username остаётся пустым, сервер решит; лучше заполнить явно).
        val username = extra.optString("username").ifBlank {
            extra.optString("user").ifBlank { if (':' in profile.uuidOrPassword) profile.uuidOrPassword.substringBefore(':') else "" }
        }
        // password: явное поле → `user:pass` (после ':') → uuidOrPassword целиком
        val password = extra.optString("password").ifBlank {
            if (':' in profile.uuidOrPassword) profile.uuidOrPassword.substringAfter(':') else profile.uuidOrPassword
        }
        val upstream = TrustTunnelConfig.UpstreamProtocol.parse(
            extra.optString("upstream_protocol").ifBlank { profile.transport.takeIf { it.isNotBlank() && it != "tcp" } ?: "http2" }
        )
        val insecure = extra.optBoolean("insecure", false) || extra.optBoolean("skip_verification", false) || profile.security == "insecure"
        val sni = profile.sni.ifBlank { extra.optString("sni") }
        val hostname = sni.ifBlank { profile.address }
        return TrustTunnelConfig(
            hostname = extra.optString("hostname").ifBlank { hostname },
            addresses = listOf(address),
            username = username,
            password = password,
            upstreamProtocol = upstream,
            tlsProfile = extra.optString("tls_profile").ifBlank { profile.fingerprint.ifBlank { "chrome" } },
            skipVerification = insecure,
            certificatePem = extra.optString("certificate").ifBlank { null },
            hasIpv6 = extra.optBoolean("has_ipv6", true),
            clientRandom = extra.optString("client_random"),
            clientRandomAuthKey = extra.optString("client_random_auth_key"),
            antiDpi = extra.optBoolean("anti_dpi", false),
            dnsUpstreams = extra.optJSONArray("dns_upstreams")?.let { a -> (0 until a.length()).map { a.optString(it) } }.orEmpty(),
            name = profile.name.ifBlank { null },
            customSni = sni.ifBlank { null },
        )
    }

    private fun hostForAddress(addr: String): String =
        if (':' in addr && !addr.startsWith("[") && addr.count { it == ':' } > 1) "[$addr]" else addr  // голый IPv6 → [..]

    /** TOML basic-string экранирование. */
    private fun toml(s: String): String = "\"" + s
        .replace("\\", "\\\\").replace("\"", "\\\"")
        .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + "\""
}
